package handlers

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"strings"
	"time"

	"github.com/wirewarp/agent/internal/config"
)

type EdgeDisableParams struct {
	PreserveState bool     `json:"preserve_state"`
	Services      []string `json:"services"`
}

var edgeSystemctl = func(ctx context.Context, args ...string) ([]byte, error) {
	sysctl := resolveBin("systemctl", "/usr/bin/systemctl", "/bin/systemctl")
	return exec.CommandContext(ctx, sysctl, args...).CombinedOutput()
}

func (h *EdgeHandlers) handleEdgeDisable(raw json.RawMessage) (string, error) {
	var p EdgeDisableParams
	if len(raw) > 0 {
		if err := json.Unmarshal(raw, &p); err != nil {
			return "", fmt.Errorf("parse params: %w", err)
		}
	}
	if err := h.cfg.UpdateAndSave(h.cfgPath, func(next *config.Config) error {
		next.EdgeDisabled = true
		return nil
	}); err != nil {
		return "", fmt.Errorf("persist disabled edge state: %w", err)
	}
	return h.stopDisabledEdge(p.Services)
}

func (h *EdgeHandlers) stopDisabledEdge(services []string) (string, error) {
	output, stopErr := h.stopEdgeServices(services)
	if stopErr != nil {
		return output, stopErr
	}
	requestedTraefik := false
	for _, service := range normalizeEdgeServices(services) {
		unit, _ := edgeServiceUnit(service)
		if unit == traefikUnitName {
			requestedTraefik = true
		}
	}
	if !requestedTraefik {
		return output + "; retained ingress guard until Traefik is stopped", nil
	}
	if ingressErr := h.removeEdgeIngress(); ingressErr != nil {
		return output, fmt.Errorf("remove edge ingress: %w", ingressErr)
	}
	if err := h.cfg.UpdateAndSave(h.cfgPath, func(next *config.Config) error {
		next.EdgeIngressGuard = nil
		next.EdgeRuntimePending = false
		return nil
	}); err != nil {
		return output, fmt.Errorf("persist cleared edge ingress guard: %w", err)
	}
	return output, nil
}

func (h *EdgeHandlers) stopEdgeServices(requested []string) (string, error) {
	services := normalizeEdgeServices(requested)
	ctx, cancel := context.WithTimeout(context.Background(), 45*time.Second)
	defer cancel()

	var stopped []string
	var skipped []string
	var unmanaged []string
	var failures []string
	for _, service := range services {
		unit, ok := edgeServiceUnit(service)
		if !ok {
			failures = append(failures, fmt.Sprintf("%s: unsupported service", service))
			continue
		}
		owned, err := h.ownedService(unit)
		if err != nil {
			failures = append(failures, fmt.Sprintf("%s: inspect managed service: %v", unit, err))
			continue
		}
		if !owned {
			unmanaged = append(unmanaged, unit)
			continue
		}
		out, err := edgeSystemctl(ctx, "disable", "--now", unit)
		msg := strings.TrimSpace(string(out))
		if err == nil {
			stopped = append(stopped, unit)
			continue
		}
		if isMissingSystemdUnit(msg) {
			skipped = append(skipped, unit)
			continue
		}
		if msg == "" {
			msg = err.Error()
		}
		failures = append(failures, fmt.Sprintf("%s: %s", unit, msg))
	}
	if len(failures) > 0 {
		return "", fmt.Errorf("disable edge services: %s", strings.Join(failures, "; "))
	}

	parts := []string{}
	if len(unmanaged) > 0 {
		parts = append(parts, "skipped unmanaged "+strings.Join(unmanaged, ", "))
	}
	if len(stopped) > 0 {
		parts = append(parts, "stopped/disabled "+strings.Join(stopped, ", "))
	}
	if len(skipped) > 0 {
		parts = append(parts, "skipped missing "+strings.Join(skipped, ", "))
	}
	if len(parts) == 0 {
		parts = append(parts, "no edge services requested")
	}
	return strings.Join(parts, "; ") + "; preserved configs and saved desired state", nil
}

func managedEdgeService(unit string) (bool, error) {
	switch unit {
	case traefikUnitName:
		return managedFileContains(traefikUnitPath, "Description=Traefik edge proxy (WireWarp-managed)")
	case "nginx":
		return managedFileContains(nginxCacheConfigPath, "# AUTO-GENERATED by wirewarp-agent")
	case "crowdsec":
		return managedFileContains(crowdSecWhitelistFile, "name: wirewarp/auto-whitelist")
	}
	return false, nil
}

func (h *EdgeHandlers) ownedService(unit string) (bool, error) {
	if h.managedService != nil {
		return h.managedService(unit)
	}
	return managedEdgeService(unit)
}

func managedFileContains(path, marker string) (bool, error) {
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	return strings.Contains(string(data), marker), nil
}

func normalizeEdgeServices(in []string) []string {
	if len(in) == 0 {
		return []string{"traefik", "crowdsec", "nginx"}
	}
	seen := map[string]bool{}
	out := make([]string, 0, len(in))
	for _, service := range in {
		service = strings.TrimSpace(strings.ToLower(service))
		if service == "" || seen[service] {
			continue
		}
		seen[service] = true
		out = append(out, service)
	}
	return out
}

func edgeServiceUnit(service string) (string, bool) {
	switch service {
	case "traefik", "traefik.service":
		return traefikUnitName, true
	case "crowdsec", "crowdsec.service":
		return "crowdsec", true
	case "nginx", "nginx.service", "nginx_cache", "nginx-cache":
		return "nginx", true
	default:
		return "", false
	}
}

func isMissingSystemdUnit(output string) bool {
	output = strings.ToLower(output)
	return strings.Contains(output, "could not be found") ||
		strings.Contains(output, "not found") ||
		strings.Contains(output, "not loaded") ||
		strings.Contains(output, "does not exist") ||
		strings.Contains(output, "no such file")
}
